// node tests/test_mining_health.js
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context={window:{}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('js/mining-health.js','utf8'),context);
const {evaluate,render}=context.window.MiningHealth;
const now=1800000000000;
const fresh=(coin='BTC')=>({fetched_at:now/1000,stale:false,data:{coin,hashrate:82.5,unit:'TH/s',workers:{all:1,online:1,offline:0,dead:2}}});
assert.equal(evaluate(fresh(),false,now).level,'healthy'); // Historical dead workers do not invalidate current online miners.
assert.equal(evaluate(null,false,now).label,'Checking');
assert.equal(evaluate(fresh(),true,now).level,'warning');
let d=fresh();d.stale=true;
assert.equal(evaluate(d,false,now).label,'Stale data');
assert.equal(evaluate(fresh(),false,now+180001).level,'warning');
d=fresh();d.fetched_at=NaN;
assert.equal(evaluate(d,false,now).level,'warning');
d=fresh();d.fetched_at+=10;
assert.equal(evaluate(d,false,now).level,'warning');
d=fresh();d.data.hashrate=0;
assert.equal(evaluate(d,false,now).label,'Not mining');
d=fresh();d.data.workers={all:1,online:0,offline:1};
assert.equal(evaluate(d,false,now).level,'down');
d=fresh();d.data.workers={all:3,online:2,offline:1};
assert.equal(evaluate(d,false,now).label,'Partly offline');
d=fresh();d.data.workers={all:0,online:0,offline:0};
assert.equal(evaluate(d,false,now).level,'down');
d=fresh();d.data.workers={all:3,online:1,offline:0};
assert.equal(evaluate(d,false,now).label,'Unknown');
d=fresh();d.data.hashrate=NaN;
assert.equal(evaluate(d,false,now).level,'warning');
const target={dataset:{}};
const states=[{coin:'btc',summaryResult:fresh()},{coin:'aleo',summaryResult:fresh('ALEO')}];
render(target,states,now);
assert.match(target.className,/status-all-green/);
assert.equal((target.innerHTML.match(/chip-green/g)||[]).length,2);
render(target,states,now+180001);
assert.match(target.className,/status-mining-warning/);
assert.doesNotMatch(target.innerHTML,/chip-green/);
states[1].summaryFailed=true;
render(target,states,now);
assert.match(target.innerHTML,/Unavailable/);
assert.equal((target.innerHTML.match(/chip-green/g)||[]).length,1);
states[1].summaryFailed=false;states[1].summaryResult.data.hashrate=0;
render(target,states,now);
assert.match(target.className,/status-has-issues/);
assert.match(target.innerHTML,/Not mining/);
states[1].summaryResult=fresh('ALEO');
render(target,states,now);
assert.match(target.className,/status-all-green/);
states.push({coin:'prl',summaryResult:fresh('PRL')});
render(target,states,now);
assert.match(target.innerHTML,/F2POOL REPORTS BTC & ALEO & PRL MINING/);
assert.equal((target.innerHTML.match(/chip-green/g)||[]).length,3);
states[2].summaryFailed=true;
render(target,states,now);
assert.match(target.className,/status-mining-warning/);
assert.match(target.innerHTML,/PRL:<\/span><strong>Unavailable/);
states[2].summaryFailed=false;
states[2].summaryResult.data.hashrate=0;
render(target,states,now);
assert.match(target.className,/status-has-issues/);
console.log('Mining health tests passed');
